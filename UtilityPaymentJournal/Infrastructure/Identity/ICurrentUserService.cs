namespace UtilityPaymentJournal.Infrastructure.Identity
{
    /// <summary>
    /// Интерфейс инфраструктурного сервиса для предоставления данных о текущем контексте пользователя.
    /// Отвечает за безопасное извлечение идентификатора авторизованного субъекта из метаданных HTTP-запроса.
    /// </summary>
    public interface ICurrentUserService
    {
        /// <summary>
        /// Уникальный строковый идентификатор (ID) пользователя в системе Identity, зафиксированный в текущей сессии.
        /// Возвращает null, если запрос выполняется анонимным гостем.
        /// </summary>
        string? UserId { get; }
    }
}
